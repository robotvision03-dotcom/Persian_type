def _expand_surnames() -> tuple[str, ...]:
    out: set[str] = set(_SURNAME_EXTRA)
    suffixes = ("پور", "زاده", "نژاد", "فر", "نیا")
    for stem in _SURNAME_STEMS:
        clean = stem.strip()
        if not clean:
            continue
        out.add(clean)
        if not clean.endswith("ی"):
            out.add(clean + "ی")
        for suffix in suffixes:
            out.add(clean + suffix)
        if not clean.endswith("یان"):
            out.add(clean + "یان")
    return tuple(sorted(out))


FAMILY_NAMES: tuple[str, ...] = _expand_surnames()


@dataclass
class PersonHit:
    given: str = ""
    family: str = ""
    full: str = ""
    score: int = 0
    candidates: list[str] = field(default_factory=list)

    def as_dict(self) -> dict[str, Any]:
        return {
            "given": self.given,
            "family": self.family,
            "full": self.full,
            "score": self.score,
            "candidates": list(self.candidates),
        }


def _best_name(token: str, lexicon: tuple[str, ...], aliases: dict[str, str]) -> tuple[str, int]:
    folded = fold(token)
    if not folded:
        return token, 0
    for key, canonical in aliases.items():
        if fold(key) == folded or compact(key) == compact(token):
            return canonical, 100
    best_name = token
    best = 0
    for name in lexicon:
        score = name_score(token, name)
        if score > best:
            best = score
            best_name = name
        if score == 100:
            return name, 100
    if best >= 72:
        return best_name, best
    return token, best


def _strip_fillers(text: str) -> list[str]:
    tokens = [part for part in fold(text).split() if part and part not in FILLERS]
    return tokens


def match_person_name(text: str) -> PersonHit:
    """Repair a spoken Iranian full name against the given/family catalogs."""
    raw = (text or "").strip()
    if not raw:
        return PersonHit()
    tokens = _strip_fillers(raw)
    if not tokens:
        return PersonHit(full=raw)

    given = ""
    family_tokens: list[str] = []
    score = 0

    if len(tokens) >= 2:
        pair = (fold(tokens[0]), fold(tokens[1]))
        for left, right in COMPOUND_GIVEN:
            if pair == (fold(left), fold(right)):
                compact_form = {
                    ("امیر", "حسین"): "امیرحسین",
                    ("امیر", "رضا"): "امیررضا",
                    ("امیر", "محمد"): "امیرمحمد",
                    ("امیر", "علی"): "امیرعلی",
                    ("امیر", "عباس"): "امیرعباس",
                    ("محمد", "رضا"): "محمدرضا",
                    ("محمد", "حسین"): "محمدحسین",
                    ("محمد", "علی"): "محمدعلی",
                    ("محمد", "مهدی"): "محمدمهدی",
                    ("محمد", "امین"): "محمدامین",
                    ("محمد", "جواد"): "محمدجواد",
                    ("علی", "رضا"): "علیرضا",
                    ("حمید", "رضا"): "حمیدرضا",
                    ("فاطمه", "زهرا"): "فاطمه زهرا",
                }
                given = compact_form.get((left, right), f"{left} {right}")
                family_tokens = tokens[2:]
                score = 100
                break

    if not given:
        given, gscore = _best_name(tokens[0], GIVEN_NAMES, GIVEN_ALIASES)
        score = gscore
        family_tokens = tokens[1:]

    family_parts: list[str] = []
    for token in family_tokens:
        name, fscore = _best_name(token, FAMILY_NAMES, FAMILY_ALIASES)
        family_parts.append(name)
        score = max(score, fscore)

    family = " ".join(family_parts).strip()
    full = " ".join(part for part in (given, family) if part).strip() or raw
    return PersonHit(given=given, family=family, full=full, score=score)


def name_catalog_counts() -> dict[str, int]:
    return {"given": len(GIVEN_NAMES), "family": len(FAMILY_NAMES)}
